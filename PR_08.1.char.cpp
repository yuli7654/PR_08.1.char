// Дано літерний рядок, який містить послідовність символів
// s[0], ..., s[n], ...
// 1. Вияснити, чи є в цій послідовності такі елементи s[i–1] , s[i+1]
// що s[i–1] – це кома (','), а s[i+1] – тире ('-'),
// та обчислити їх кількість.
// 2. Замінити кожну групу символів s[i–1] , s[i] , s[i+1] – таких, що
// s[i–1] – це кома (','), а s[i+1] – тире ('-')
// парою зірочок "**".

// #pragma працює незалежно від порядку #include, на відміну від #define:
// у проєкті unit-тестів заголовки підключаються раніше за цей файл.
#define _CRT_SECURE_NO_WARNINGS
#include <cstring>
#include <iostream>

using namespace std;

// Count – обчислює кількість груп s[i-1], s[i], s[i+1], у яких
//         s[i-1] == ',' та s[i+1] == '-' (символ s[i] – будь-який).
// s     – вказівник на початок літерного рядка (функція його не змінює).
// Повертає кількість груп; 0 означає, що таких елементів у рядку немає.
int Count(char* s)
{
    int k = 0,    // k – лічильник знайдених груп
        pos = 0;  // pos – позиція початку пошуку коми
    char* t;      // t – вказівник на знайдену кому

    // strchr шукає кому, починаючи з позиції pos;
    // якщо коми більше немає – повертає 0
    while ((t = strchr(s + pos, ',')))
    {
        // pos = позиція символу після коми, тобто s[i]
        pos = t - s + 1;
        // s[pos] != 0 – після коми є символ s[i] (інакше s[pos+1] було б
        // за межами рядка); s[pos+1] == '-' – символ s[i+1] є тире
        if (s[pos] != 0 && s[pos + 1] == '-')
            k++;
    }
    return k;
}

// Change – замінює кожну групу ',' <будь-який символ> '-' парою "**".
// s      – вказівник на початок літерного рядка: результат повертається
//          і через цей параметр (він змінюється), і як значення функції.
// Повертає вказівник на новий рядок t (пам'ять виділена через new[]).
char* Change(char* s)
{
    // Групу з 3 символів замінюємо на 2 зірочки, тож результат не довший
    // за вхідний рядок. +1 – місце для нуль-символу.
    char* t = new char[strlen(s) + 1];
    char* p;       // p – вказівник на знайдену кому
    int pos1 = 0,  // pos1 = позиція початку ще не скопійованої частини s
        pos2 = 0;  // pos2 = позиція, з якої продовжимо копіювання і пошук
    *t = 0;        // спочатку t – порожній рядок

    while ((p = strchr(s + pos1, ',')))  // p = вказівник на кому
    {
        // s[p-s+1] != 0 – після коми є символ (інакше s[p-s+2] було б за
        // межами рядка); s[p-s+2] == '-' – через один символ стоїть тире,
        // тобто група знайдена
        if (s[p - s + 1] != 0 && s[p - s + 2] == '-')
        {
            pos2 = p - s + 3;  // pos2 = позиція символа після '-'
            // копіюємо частину рядка перед комою (від pos1 до коми)...
            strncat(t, s + pos1, pos2 - pos1 - 3);
            // ...і замість групи з трьох символів дописуємо дві зірочки
            strcat(t, "**");
            pos1 = pos2;
        }
        else
        {
            pos2 = p - s + 1;  // pos2 = позиція символа після коми
            // копіюємо все від pos1 до коми включно
            strncat(t, s + pos1, pos2 - pos1);
            pos1 = pos2;
        }
    }
    strcat(t, s + pos1);  // дописуємо решту рядка після останньої коми
    strcpy(s, t);         // результат повертаємо через параметр s
    return t;             // ... і як значення функції
}

int main()
{
    char str[101];
    cout << "Enter string:" << endl;
    cin.getline(str, 100);

    cout << "String contained " << Count(str) << " groups of ', -'" << endl;

    char* dest = new char[151];
    dest = Change(str);
    cout << "Modified string (param) : " << str << endl;
    cout << "Modified string (result): " << dest << endl;
    return 0;
}